class RadarRequestHandler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        parsed_url = urllib.parse.urlparse(self.path)

        if parsed_url.path == '/' or parsed_url.path.startswith('/?'):
            self.send_response(200)
            self.send_header('Content-Type', 'text/html; charset=utf-8')
            self.end_headers()
            self.wfile.write(HTML_PAGE.encode('utf-8'))

        elif parsed_url.path == '/data':
            query_params = urllib.parse.parse_qs(parsed_url.query)
            lat = float(query_params.get('lat', [DEFAULT_LAT])[0])
            lon = float(query_params.get('lon', [DEFAULT_LON])[0])

            radar_json = fetch_radar_data(lat, lon)

            self.send_response(200)
            self.send_header('Content-Type', 'application/json; charset=utf-8')
            self.send_header('Access-Control-Allow-Origin', '*')
            self.end_headers()
            self.wfile.write(json.dumps(radar_json).encode('utf-8'))
        else:
            self.send_response(404)
            self.end_headers()

    def log_message(self, format, *args):
        return

def run_application():
    if hasattr(sys, '_colab_radar_server'):
        try:
            sys._colab_radar_server.shutdown()
            sys._colab_radar_server.server_close()
        except Exception:
            pass

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(('', 0))
        port = s.getsockname()[1]

    class ReusableTCPServer(socketserver.TCPServer):
        allow_reuse_address = True

    server = ReusableTCPServer(("", port), RadarRequestHandler)
    sys._colab_radar_server = server

    threading.Thread(target=server.serve_forever, daemon=True).start()
    print(f"Interactive Radar server running on port {port}.")
    output.serve_kernel_port_as_iframe(port, height=760)

run_application()