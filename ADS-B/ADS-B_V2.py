def haversine(lat1, lon1, lat2, lon2):
    R = 6371.0
    dlat = math.radians(lat2 - lat1)
    dlon = math.radians(lon2 - lon1)
    a = (math.sin(dlat / 2) ** 2 +
         math.cos(math.radians(lat1)) * math.cos(math.radians(lat2)) *
         math.sin(dlon / 2) ** 2)
    return R * (2 * math.atan2(math.sqrt(a), math.sqrt(1 - a)))

def feet_to_meters(feet):
    try:
        return round(float(feet) * 0.3048) if feet not in (None, "ground") else 0
    except (ValueError, TypeError):
        return "N/A"

def knots_to_kmh(knots):
    try:
        return round(float(knots) * 1.852) if knots is not None else "N/A"
    except (ValueError, TypeError):
        return "N/A"

def get_airline_from_callsign(callsign):
    if not callsign or callsign == "N/A":
        return "General / Private"
    prefix = callsign.strip().upper()[:3]
    return KNOWN_AIRLINES.get(prefix, "General / Private")

def query_adsb_api(lat, lon):
    """Executes fast requests to ADS-B APIs for target dynamic coordinates."""
    primary_url = f"https://opendata.adsb.fi/api/v3/lat/{lat}/lon/{lon}/dist/{RADIUS_NM}"
    fallback_url = f"https://api.adsb.lol/v2/lat/{lat}/lon/{lon}/dist/{RADIUS_NM}"

    headers = {"User-Agent": "Mozilla/5.0"}

    try:
        req = urllib.request.Request(primary_url, headers=headers)
        with urllib.request.urlopen(req, timeout=2.5) as resp:
            if resp.status == 200:
                return json.loads(resp.read().decode("utf-8"))
    except Exception:
        pass

    try:
        req = urllib.request.Request(fallback_url, headers=headers)
        with urllib.request.urlopen(req, timeout=2.5) as resp:
            if resp.status == 200:
                return json.loads(resp.read().decode("utf-8"))
    except Exception:
        pass

    return None

def fetch_radar_data(center_lat, center_lon):
    """Fetches aircraft data within 150 km of specified coordinates."""
    raw = query_adsb_api(center_lat, center_lon)
    aircraft_list = []

    if raw and "ac" in raw:
        for ac in raw.get("ac", []):
            lat, lon = ac.get("lat"), ac.get("lon")
            if lat is None or lon is None:
                continue

            dist_km = haversine(center_lat, center_lon, lat, lon)
            if dist_km > RADIUS_KM:
                continue

            hex_id = str(ac.get("hex", "")).upper().strip()
            raw_callsign = ac.get("flight", "")
            callsign = raw_callsign.strip() if raw_callsign else "N/A"
            target_id = hex_id if hex_id != "" else callsign

            if not target_id or target_id == "N/A":
                continue

            aircraft_list.append({
                "id": target_id,
                "hex": hex_id,
                "callsign": callsign,
                "airline": get_airline_from_callsign(callsign),
                "lat": lat,
                "lon": lon,
                "distance_km": round(dist_km, 1),
                "altitude_m": feet_to_meters(ac.get("alt_baro")),
                "speed_kmh": knots_to_kmh(ac.get("gs")),
                "track": round(float(ac.get("track", 0) or 0), 1),
                "aircraft_type": ac.get("t", "N/A"),
                "registration": ac.get("r", "N/A")
            })

    return {
        "timestamp": time.strftime("%H:%M:%S"),
        "center": {"lat": center_lat, "lon": center_lon},
        "count": len(aircraft_list),
        "aircraft": aircraft_list
    }

